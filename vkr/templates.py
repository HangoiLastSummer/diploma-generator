def chapter_md(n, title, subs, type_name):
    out = [f"<!--\nГлава {n} (тип работы: {type_name}, методичка, раздел 2).\n"
           "Номера глав и подразделов не пиши — их ставит генератор. Каждый подраздел начинается и заканчивается текстом.\n-->\n",
           f"# {title}\n"]
    for t, vol, task, srcs in subs:
        out.append(f"## {t}\n")
        c = f"<!-- ЗАДАНИЕ: {task}\n     ОБЪЁМ: {vol} стр."
        if srcs:
            c += f"\n     ИСТОЧНИК ФАКТОВ: {srcs}"
        out.append(c + " -->\n")
    return "\n".join(out)


